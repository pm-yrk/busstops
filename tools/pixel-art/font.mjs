export function textWidth(text) {
  return text.length * 4 - 1;
}

/** Draws `text` at (x, y) in colour `c`. Returns the width used. */
export function text(canvas, x, y, str, c) {
  let cx = x;
  for (const ch of str.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "];
    glyph.forEach((row, j) =>
      row.split("").forEach((bit, i) => {
        if (bit === "1") canvas.px(cx + i, y + j, c);
      }),
    );
    cx += 4;
  }
  return cx - x - 1;
}
